#!/bin/sh
# Rebuilds firmware/include/certs.h from the system CA store (Debian/Ubuntu paths).
set -e
OUT="$(dirname "$0")/../include/certs.h"
{
echo '// Root CA certificates the logger trusts for HTTPS (srv_url starting with https://).'
echo "// Caddy gets its certificate from Let's Encrypt (ISRG roots) or, as a fallback, ZeroSSL"
echo '// (USERTrust roots). Generated by firmware/tools/make_certs.sh from the Debian CA store.'
echo '#pragma once'
echo 'static const char CA_BUNDLE[] ='
for f in ISRG_Root_X1 ISRG_Root_X2 USERTrust_RSA_Certification_Authority USERTrust_ECC_Certification_Authority; do
  echo "  // $f"
  sed 's/^/  "/; s/$/\\n"/' /etc/ssl/certs/$f.pem
done
echo '  ;'
} > "$OUT"
echo "wrote $OUT"
